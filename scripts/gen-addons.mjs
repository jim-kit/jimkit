#!/usr/bin/env node
// Finds the addons to build in, reads their manifests, and writes the registry the app imports.
//
//   addons/<id>/            first-party and local addons (npm workspace packages)
//   node_modules/jimkit-addon-*, node_modules/@scope/jimkit-addon-*     addons installed from npm
//   jimkit.config.json      { "addons": ["text", "hash"] }  or  { "addons": "*" }
//
// Output goes to apps/web/src/generated/ (git-ignored): addons.client.ts, addons.server.ts, manifests.json, packages.json, sources.css, themes.css.
import { existsSync, mkdirSync, readFileSync, readdirSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { settingsProblem } from "../packages/sdk/src/bundle.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "apps/web/src/generated");
const API_VERSION = 1;

const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));

/** Every package that declares a "jimkit" manifest. */
export function discover(base = root) {
  const found = new Map();
  const consider = (dir) => {
    const pj = join(dir, "package.json");
    if (!existsSync(pj)) return;
    const pkg = readJson(pj);
    if (!pkg.jimkit?.id) return;
    const real = realpathSync(dir);
    const manifest = { ...pkg.jimkit, version: pkg.jimkit.version ?? pkg.version ?? "0.0.0", apiVersion: pkg.jimkit.apiVersion ?? API_VERSION };
    manifest.client = existsSync(join(real, "src/client.ts")) || existsSync(join(real, "src/client.tsx"));
    manifest.server = existsSync(join(real, "src/server.ts")) || existsSync(join(real, "src/server.tsx"));
    if (found.has(manifest.id) && found.get(manifest.id).dir === real) return; // the same package seen twice (workspace symlink)
    if (found.has(manifest.id)) throw new Error(`Two addons are both called "${manifest.id}": ${found.get(manifest.id).dir} and ${real}`);
    found.set(manifest.id, { id: manifest.id, name: pkg.name, dir: real, manifest });
  };
  const scan = (dir) => existsSync(dir) && readdirSync(dir, { withFileTypes: true }).filter((e) => e.isDirectory() || e.isSymbolicLink()).forEach((e) => consider(join(dir, e.name)));
  scan(join(base, "addons"));
  const nm = join(base, "node_modules");
  if (existsSync(nm)) {
    for (const e of readdirSync(nm, { withFileTypes: true })) {
      if (e.name.startsWith("jimkit-addon-")) consider(join(nm, e.name));
      else if (e.name.startsWith("@")) {
        for (const s of readdirSync(join(nm, e.name), { withFileTypes: true })) if (s.name.startsWith("jimkit-addon-") || (e.name === "@jimkit" && s.name.startsWith("addon-"))) consider(join(nm, e.name, s.name));
      }
    }
  }
  return [...found.values()];
}

/** A malformed settings declaration should stop the build, not show up as a broken Settings panel. */
export function checkSettings(id, defs) {
  const problem = settingsProblem(defs);
  if (problem) { console.error(`Addon "${id}": settings: ${problem}`); process.exit(1); }
}

function main() {
  const config = existsSync(join(root, "jimkit.config.json")) ? readJson(join(root, "jimkit.config.json")) : { addons: "*" };
  const all = discover();
  const want = config.addons === "*" || !config.addons ? all.map((a) => a.id) : config.addons;
  const missing = want.filter((id) => !all.some((a) => a.id === id));
  if (missing.length) {
    console.error(`jimkit.config.json lists addons that aren't installed: ${missing.join(", ")}\nInstalled: ${all.map((a) => a.id).join(", ") || "none"}`);
    process.exit(1);
  }
  const chosen = all.filter((a) => want.includes(a.id)).sort((a, b) => want.indexOf(a.id) - want.indexOf(b.id));
  for (const a of chosen) {
    checkSettings(a.id, a.manifest.settings);
    if (a.manifest.apiVersion !== API_VERSION) {
      console.error(`Addon "${a.id}" targets addon API ${a.manifest.apiVersion}, this Jimkit speaks ${API_VERSION}.`);
      process.exit(1);
    }
  }

  mkdirSync(out, { recursive: true });
  const spec = (a, entry) => `${a.name}/${entry}`;
  const header = "// Generated by scripts/gen-addons.mjs. Do not edit; do not commit.\n";

  writeFileSync(
    join(out, "addons.client.ts"),
    header +
      `import type { ClientModule } from "@jimkit/sdk";\n\n` +
      `/** One lazy loader per addon: nothing from an addon is in the first page load. */\n` +
      `export const clientLoaders: Record<string, () => Promise<{ default: ClientModule }>> = {\n` +
      chosen.filter((a) => a.manifest.client).map((a) => `  ${JSON.stringify(a.id)}: () => import(${JSON.stringify(spec(a, "client"))}),\n`).join("") +
      `};\n`,
  );
  writeFileSync(
    join(out, "addons.server.ts"),
    header +
      `import type { ServerModule } from "@jimkit/sdk";\n\n` +
      `export const serverLoaders: Record<string, () => Promise<{ default: ServerModule }>> = {\n` +
      chosen.filter((a) => a.manifest.server).map((a) => `  ${JSON.stringify(a.id)}: () => import(${JSON.stringify(spec(a, "server"))}),\n`).join("") +
      `};\n`,
  );
  writeFileSync(join(out, "manifests.json"), JSON.stringify(chosen.map((a) => a.manifest), null, 2));
  writeFileSync(join(out, "packages.json"), JSON.stringify(chosen.map((a) => a.name)));
  // Tailwind only generates classes it can see: point it at every addon's source
  writeFileSync(
    join(out, "sources.css"),
    "/* Generated by scripts/gen-addons.mjs. Do not edit; do not commit. */\n" + chosen.map((a) => `@source ${JSON.stringify(relative(out, join(a.dir, "src")))};`).join("\n") + "\n",
  );
  // the stylesheets of the themes the addons bring (plain CSS, every rule scoped to its own theme); an addon without one adds nothing
  writeFileSync(
    join(out, "themes.css"),
    "/* Generated by scripts/gen-addons.mjs. Do not edit; do not commit. */\n" +
      chosen.filter((a) => existsSync(join(a.dir, "src/theme.css"))).map((a) => `@import ${JSON.stringify(relative(out, join(a.dir, "src/theme.css")))};`).join("\n") + "\n",
  );
  console.log(`jimkit: ${chosen.length} addon${chosen.length === 1 ? "" : "s"} built in: ${chosen.map((a) => a.id).join(", ")}`);
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) main();
